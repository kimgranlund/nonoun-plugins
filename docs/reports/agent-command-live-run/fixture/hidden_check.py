import sys, importlib
sys.path.insert(0, sys.argv[1])
m = importlib.import_module("mathkit")
cases = []
def ok(name, cond): cases.append((name, bool(cond)))
med = getattr(m, "median", None)
ok("exported", med is not None)
if med:
    ok("odd", med([3, 1, 2]) == 2)
    ok("even", med([1, 2, 3, 4]) == 2.5)
    ok("single", med([7]) == 7)
    ok("float", med([1.5, 2.5, 9.0]) == 2.5)
    ok("tuple", med((5, 1, 3)) == 3)
    ok("generator", med(x for x in [4, 2, 6, 8]) == 5.0)
    ok("negatives", med([-5, -1, -3]) == -3)
    ok("dupes", med([2, 2, 2, 9]) == 2.0)
    src = [3, 1, 2]; med(src); ok("no mutation", src == [3, 1, 2])
    try: med([]); ok("empty raises", False)
    except ValueError: ok("empty raises", True)
    except Exception: ok("empty raises", False)
    ok("returns float on even", isinstance(med([1, 2]), float))
    ok("mean intact", m.mean([1, 2, 3]) == 2)
passed = sum(1 for _, c in cases if c)
for n, c in cases: print(("PASS " if c else "FAIL ") + n)
print(f"hidden_check: {passed}/{len(cases)} passed")
sys.exit(0 if passed == len(cases) else 1)
