#!/usr/bin/env python3
"""Generate/install native Codex agents and optional project factory guidance (Python 3.9+)."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ADAPTER = ROOT / 'adapters/codex'
TOKEN = '@SDLC_PLUGIN_ROOT@'
REQUIRED = {'name', 'description', 'model', 'model_reasoning_effort', 'sandbox_mode', 'developer_instructions'}
FACTORY_MARKER = '<!-- SDLC Codex project factory'
FACTORY_TEXT = (
    'For this project, act as the SDLC factory for software delivery work. '
    'Load the installed sdlc skill, follow its workflow routing, and coordinate '
    'implementation and verification through the configured SDLC roles and runner. '
    'Honor the user\'s instructions and the project\'s existing guidance.'
)

FIELDS = REQUIRED


def body(path):
    text = path.read_text()
    return text.split('---', 2)[2].strip() if text.startswith('---\n') else text.strip()


ALTERNATES = 'verifier_alternates'
# Checking role -> producing role whose newest result's model it must not share. The alternates
# map keeps its verifier_alternates name and serves every role here (T-0171).
PAIRED = {'verifier': 'builder', 'plan-reviewer': 'planner'}


def config():
    return json.loads((ADAPTER / 'models.json').read_text())


def models():
    """Role entries only: {role: {level: [model, effort]}}."""
    return {role: levels for role, levels in config().items() if role != ALTERNATES}


def verifier_alternates():
    """Producer model -> model a PAIRED checking role uses when its own configured model equals it. Empty means share."""
    return dict(config().get(ALTERNATES) or {})


def instructions(role, level):
    """The role contract for one row; a level with a section in overlays/<role>.md gets it before `## Output`."""
    import claude_roles
    src = ROOT / 'agents' / (role + '.md')
    text = src.read_text()
    header = text.split('---', 2)[1]
    skills = re.findall(r'^  - ([a-z-]+)$', header, re.M)
    prelude = (ADAPTER / 'instructions.md').read_text()
    contract = body(src)
    sections = claude_roles.overlay(ROOT, role)
    if level in sections:
        contract = claude_roles.insert_overlay(contract, level, sections[level])
    parts = [prelude, '# Shared role contract\n' + contract]
    for skill in skills:
        parts.append('# Required skill: ' + skill + '\nResources: ' + TOKEN + '/skills/' + skill + '/\n' + body(ROOT / 'skills' / skill / 'SKILL.md'))
    return '\n\n'.join(parts).replace('${CLAUDE_PLUGIN_ROOT}', TOKEN)


def dumps(data):
    # JSON-escaped strings with literal Unicode are valid TOML strings; surrogate escapes are not. Keep the generated subset dependency-free.
    return '# Generated by scripts/codex_roles.py; edit the shared sources, then regenerate.\n' + ''.join(k + ' = ' + json.dumps(v, ensure_ascii=False) + '\n' for k, v in data.items())


def loads(path):
    data = {}
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        key, value = line.split('=', 1)
        key = key.strip()
        if key not in FIELDS or key in data:
            raise ValueError('unsupported/duplicate generated-agent field: ' + key)
        data[key] = json.loads(value.strip())
    if not REQUIRED.issubset(data) or not all(isinstance(data[k], str) and data[k] for k in REQUIRED):
        raise ValueError('incomplete generated agent: ' + str(path))
    return data


def plugin_version():
    return json.loads((ROOT / '.claude-plugin/plugin.json').read_text())['version']


def fingerprint_of(data):
    """Plugin version plus a short hash of the generated profile (name, model, effort, sandbox, instructions)."""
    digest = hashlib.sha256(json.dumps(data, sort_keys=True, ensure_ascii=False).encode()).hexdigest()[:12]
    return plugin_version() + '+' + digest


ENVELOPE_MARK = 'the host envelope, not part of the role body'


def envelope_note(fp):
    """The appended profile section: the fingerprint line is a host envelope in front of the shared role body (T-0506)."""
    return ('\n\n# Profile fingerprint\nThis profile is revision `' + fp + '`. Before any edit, make the first line of your first message '
            'and the first line of your final report exactly `profile: ' + fp + '`. That line is ' + ENVELOPE_MARK + ': your final report is '
            'the envelope line, then the role body exactly as the shared contract defines it. The contract\'s "nothing before the first heading" '
            'means nothing between the envelope line and the first heading; the envelope is never a section. The runner stores the report as '
            'received under its result header, so a stored result keeps the envelope as its second line and the result parser skips it '
            'and validates the body.')


def envelope_conflict(instructions):
    """None, or why a profile's output instructions cannot all hold: a required `profile:` first line beside a strict
    "nothing before the first heading" rule with no stated envelope (the pre-T-0506 contradiction)."""
    if 'exactly `profile: ' in instructions and 'nothing before the first heading' in instructions and ENVELOPE_MARK not in instructions:
        return 'requires a `profile:` first line and nothing before the first heading, with no envelope rule'
    return None


def with_fingerprint(data):
    """Embed the fingerprint in the profile so the role can state the revision it loaded (T-0389)."""
    return dict(data, developer_instructions=data['developer_instructions'] + envelope_note(fingerprint_of(data)))


def fingerprint(role):
    """The fingerprint the generated profile of this exact agent name carries."""
    for name, data in definitions():
        if name == role:
            return re.search(r'revision `([^`]+)`', data['developer_instructions'])[1]
    raise KeyError(role + ': not defined by this plugin version')


def check_loaded(role, report, binding=None):
    """Compare the fingerprint a role reports it loaded with the attempt binding.

    Returns (status, message): ready (equal), refused (differs: the live session holds an older or other
    profile, and install does not change a running session), unknown (the role stated none: a handshake is
    required, and the host exposes no runtime fingerprint, so nothing claims ready)."""
    binding = binding or fingerprint(role)
    first = next((line.strip() for line in report.splitlines() if line.strip()), '')
    found = re.fullmatch(r'profile:\s*(\S+)', first.strip('`* '))
    if not found:
        return 'unknown', (f'live freshness unknown: {role} stated no loaded profile fingerprint. Handshake required: ask it to reply with the first line '
                           f'`profile: {binding}` before it edits; do not accept edits or claim ready.')
    if found[1] != binding:
        return 'refused', (f'refused: {role} loaded profile {found[1]}, the attempt binding is {binding}. Start a fresh Codex session (installing does not '
                           'change a running session), then rerun preflight and the handshake; accept no edits from this run.')
    return 'ready', f'ready: {role} loaded profile {binding}, equal to the attempt binding (live behavior beyond the profile unverified)'


def definitions():
    for name, data in raw_definitions():
        yield name, with_fingerprint(data)


def raw_definitions():
    alternates = verifier_alternates()
    for role, levels in models().items():
        for level, (model, effort) in levels.items():
            name = 'sdlc-' + role + '-' + level.lower()
            data = dict(name=name, description=f'SDLC {role} {level}. Read the handoff; follow the shared role contract.', model=model,
                            model_reasoning_effort=effort,
                            sandbox_mode='workspace-write' if role in ('builder', 'factory', 'live', 'hybrid', 'architect', 'messenger', 'solo', 'ui-designer') else 'read-only',
                            developer_instructions=instructions(role, level))
            yield name, data
            if role in PAIRED and model in alternates:
                alternate = dict(data, name=name+'-alternate', model=alternates[model])
                yield alternate['name'], alternate


def resolve(role, level, directory=None):
    """Return (model, effort, shared) for role at level.

    For a PAIRED checking role (verifier, plan-reviewer), the newest result of its producer
    (builder, planner) in directory is read; when that result's model= header equals the
    configured model, the alternate is used, or shared is True when no alternate is configured.
    shared means the checking role runs on its producer's model."""
    model, effort = models()[role][level]
    shared = False
    if role in PAIRED and directory:
        import order
        produced = order.newest(Path(directory), PAIRED[role])
        if not produced and role == 'verifier':
            # A verifier launched at the task dir reads the highest-numbered live step-<n>/ that
            # holds a builder result; the Claude twin is run.sh's verifier family rule.
            steps = []
            for child in Path(directory).iterdir():
                found = re.fullmatch(r'step-(\d+)', child.name)
                if found and child.is_dir():
                    newest = order.newest(child, 'builder')
                    if newest:
                        steps.append((int(found[1]), newest))
            if steps:
                produced = max(steps, key=lambda s: s[0])[1]
        if produced:
            match = re.search(r'\bmodel=([^\s>]+)', Path(produced).read_text())
            if match and match[1] == model:
                alternate = verifier_alternates().get(model)
                if alternate:
                    model = alternate
                else:
                    shared = True
    return model, effort, shared


def factory_block(created_key):
    mode = 'created-key' if created_key else 'appended'
    return (f'{FACTORY_MARKER}: {mode} begin -->\n'
            + FACTORY_TEXT + '\n'
            + f'{FACTORY_MARKER}: {mode} end -->')


def instruction_string(tomlkit, value):
    # TOML strips the first newline after a multiline opener. A basic string
    # with escapes preserves leading newlines in preexisting user guidance.
    return tomlkit.string(value, multiline='\n' in value and not value.startswith(('\n', '\r')))


def factory_config(project, enabled, check=False):
    """Plan a style-preserving project config edit; never change unrelated TOML."""
    path = project.resolve() / '.codex/config.toml'
    if path.parent.is_symlink() or path.is_symlink():
        raise ValueError('refusing symlinked project config destination: ' + str(path))
    if not path.exists() and not enabled:
        return path, None
    # Only the explicit project-factory commands need the vendored TOML editor.
    vendor = str(Path(__file__).resolve().parent / '_vendor')
    if vendor not in sys.path:
        sys.path.insert(0, vendor)
    import tomlkit
    if path.exists():
        with path.open('r', encoding='utf-8', newline='') as source:
            original = source.read()
    else:
        original = ''
    try:
        document = tomlkit.parse(original)
    except tomlkit.exceptions.ParseError as exc:
        raise ValueError('invalid project config TOML: ' + str(path) + ': ' + str(exc)) from exc
    had_key = 'developer_instructions' in document
    current = document.get('developer_instructions', '')
    if not isinstance(current, str):
        raise ValueError('project developer_instructions must be a string: ' + str(path))
    created = factory_block(True)
    appended = factory_block(False)
    control_markers = tuple(line for block in (created, appended)
                            for line in (block.split('\n')[0], block.split('\n')[-1]))
    if any(marker in current for marker in control_markers) and (
            sum(current.count(marker) for marker in control_markers) != 2 or
            (created in current) == (appended in current)):
        raise ValueError('refusing to change edited SDLC factory instructions: ' + str(path))
    if enabled:
        if created in current or appended in current:
            return path, None
        if check:
            raise ValueError('project factory instructions are missing: ' + str(path))
        block = appended if had_key else created
        document['developer_instructions'] = instruction_string(
            tomlkit, current + ('\n\n' if current else '') + block)
    else:
        if created in current:
            remaining = current.replace(created, '', 1)
            if remaining:
                document['developer_instructions'] = instruction_string(tomlkit, remaining)
            else:
                del document['developer_instructions']
        elif appended in current:
            # Remove only the exact managed text and the separator we inserted.
            prefix, suffix = current.split(appended, 1)
            if prefix.endswith('\n\n'):
                prefix = prefix[:-2]
            remaining = prefix + suffix
            document['developer_instructions'] = instruction_string(tomlkit, remaining)
        else:
            return path, None
    updated = tomlkit.dumps(document)
    try:
        reparsed = tomlkit.parse(updated)
    except tomlkit.exceptions.ParseError as exc:
        raise ValueError('refusing to write invalid project config TOML: ' + str(path) + ': ' + str(exc)) from exc
    if 'developer_instructions' in document and reparsed['developer_instructions'] != document['developer_instructions']:
        raise ValueError('refusing to change project developer instructions during TOML serialization: ' + str(path))
    if updated == original:
        return path, None
    return path, updated


def write_factory_config(path, updated):
    if updated is None:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise ValueError('refusing symlinked project config destination: ' + str(path))
    mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o600
    descriptor, name = tempfile.mkstemp(prefix='.config.toml.tmp-', dir=path.parent)
    temp = Path(name)
    try:
        with os.fdopen(descriptor, 'w', encoding='utf-8', newline='') as output:
            output.write(updated)
        temp.chmod(mode)
        temp.replace(path)
    finally:
        if temp.exists():
            temp.unlink()
    return True


def install(project, check=False, factory=False):
    dest = project.resolve() / '.codex/agents'
    receipt = dest / '.sdlc-managed.json'
    if dest.is_symlink() or dest.parent.is_symlink() or receipt.is_symlink():
        raise ValueError('refusing symlinked project agent destination or receipt')
    previous = json.loads(receipt.read_text()) if receipt.exists() else {}
    generated = {}
    for source in sorted((ADAPTER / 'agents').glob('*.toml')):
        data = loads(source)
        data['developer_instructions'] = data['developer_instructions'].replace(TOKEN, str(ROOT))
        generated[source.name] = dumps(data)
    generated['.gitignore'] = '# Generated SDLC agents are project-local runtime configuration.\n' + ''.join('/'+name+'\n' for name in generated) + '/.sdlc-managed.json\n/.gitignore\n'
    # Preflight every target before any write. Never overwrite user edits or unrelated agents.
    for name, text in generated.items():
        target = dest / name
        if target.is_symlink():
            raise ValueError('refusing symlinked agent: ' + str(target))
        if target.exists() and target.read_text() != text:
            digest = hashlib.sha256(target.read_bytes()).hexdigest()
            if previous.get(name) != digest:
                raise ValueError('refusing to overwrite edited/unmanaged agent: ' + str(target))
    config_path, config_text = factory_config(project, True, check) if factory else (None, None)
    if check:
        missing = [name for name, text in generated.items() if not (dest / name).exists() or (dest / name).read_text() != text]
        if missing:
            raise ValueError('agents missing or stale: ' + ', '.join(missing))
        print('Codex agents and project factory are current: ' + str(dest) if factory else 'Codex agents are current: ' + str(dest))
        return
    dest.mkdir(parents=True, exist_ok=True)
    for name, text in generated.items():
        target = dest / name
        temp = target.with_suffix('.tmp-' + str(os.getpid()))
        temp.write_text(text)
        temp.replace(target)
    receipt.write_text(json.dumps({n: hashlib.sha256(t.encode()).hexdigest() for n, t in generated.items()}, indent=2) + '\n')
    if factory:
        write_factory_config(config_path, config_text)
    print(f'Installed {len(generated)-1} project agents in {dest}'
          + (' with project factory' if factory else '') + '; start a fresh Codex session.')


def parse_catalog(text):
    """Agent names from a catalog the parent supplies: comma, space or newline separated."""
    return {name for name in re.split(r'[\s,]+', text) if name}


def preflight(project, roles, catalog):
    """Return the problems that keep roles from being callable in this session; empty means ready.

    Three facts stay separate: the plugin defines the role, the project's generated definitions are
    current (the install --check verdict, unchanged), and the role is in the callable agent catalog
    the parent read from its host. A shell script cannot inspect that catalog, so the parent supplies
    it; installed never implies loaded."""
    defined = {name for name, _ in definitions()}
    problems = []
    unknown = [role for role in roles if role not in defined]
    for role in unknown:
        problems.append(f'{role}: not defined by this plugin version. Launcher repair: update the plugin or fix the lane role name; generation and a fresh session cannot add it.')
    known = [role for role in roles if role in defined]
    drift = None
    try:
        install(project, check=True)
    except ValueError as exc:
        drift = str(exc)
    if drift is not None and known:
        if 'refusing' in drift:
            problems.append(f'definitions: {drift}. Launcher repair: resolve the edited or unmanaged file by hand; install will not overwrite it.')
        else:
            problems.append(f'definitions: {drift}. Generation required: run codex_roles.py install <project>, then start a fresh Codex session.')
    for role in known:
        if role not in catalog:
            action = 'start a fresh Codex session' if drift is None else 'after generation, start a fresh Codex session'
            problems.append(f'{role}: missing from the callable catalog of this session. Fresh session required: {action}; installed definitions are not live availability.')
    return problems


def main():
    import claude_roles
    try:
        command()
    except claude_roles.TableError as exc:
        print('codex_roles.py: ' + str(exc), file=sys.stderr)
        sys.exit(2)


def command():
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest='command', required=True)
    gen = subs.add_parser('generate'); gen.add_argument('--check', action='store_true')
    setup = subs.add_parser('install'); setup.add_argument('project', type=Path); setup.add_argument('--check', action='store_true'); setup.add_argument('--factory', action='store_true', help='opt in to the SDLC main-session factory for this project')
    off = subs.add_parser('factory-off'); off.add_argument('project', type=Path)
    pre = subs.add_parser('preflight', help='check the lane roles are defined, generated, and in the parent-supplied callable catalog')
    pre.add_argument('project', type=Path); pre.add_argument('roles', nargs='+', help='exact agent names, e.g. sdlc-solo-l2')
    pre.add_argument('--catalog', default='', help='agent names the host lists as callable in this session'); pre.add_argument('--catalog-file', type=Path, help='file of those names')
    fpr = subs.add_parser('fingerprint', help='print the profile fingerprint the generated agent carries (the attempt binding)'); fpr.add_argument('role')
    hs = subs.add_parser('handshake', help='compare the fingerprint a role reported as loaded with the attempt binding (exit 0 ready, 2 refused, 3 unknown)')
    hs.add_argument('role'); hs.add_argument('--report-file', type=Path, help="file holding the role's first message or report; absent or empty means it stated none"); hs.add_argument('--binding', help='expected fingerprint; default is the current generated profile')
    res = subs.add_parser('resolve'); res.add_argument('role'); res.add_argument('level'); res.add_argument('directory', nargs='?')
    args = parser.parse_args()
    if args.command == 'resolve':
        model, effort, shared = resolve(args.role, args.level, args.directory)
        print(model, effort, *(['shared'] if shared else []))
    elif args.command == 'fingerprint':
        print(fingerprint(args.role))
    elif args.command == 'handshake':
        status, message = check_loaded(args.role, args.report_file.read_text() if args.report_file and args.report_file.exists() else '', args.binding)
        print(message, file=sys.stdout if status == 'ready' else sys.stderr)
        sys.exit({'ready': 0, 'refused': 2, 'unknown': 3}[status])
    elif args.command == 'preflight':
        text = args.catalog + ' ' + (args.catalog_file.read_text() if args.catalog_file else '')
        catalog = parse_catalog(text)
        if not catalog:
            print('not ready: no callable catalog supplied. The parent must read the agent list its host exposes and pass it with --catalog or --catalog-file; this script cannot inspect it.', file=sys.stderr)
            sys.exit(2)
        problems = preflight(args.project, args.roles, catalog)
        if problems:
            print('not ready: ' + '; '.join(args.roles), file=sys.stderr)
            for problem in problems:
                print('- ' + problem, file=sys.stderr)
            sys.exit(2)
        print('ready: ' + ', '.join(args.roles) + ' defined, generated current, and in the supplied catalog (live behavior unverified; live freshness unknown until the handshake: '
              + '; '.join(r + ' must state `profile: ' + fingerprint(r) + '`' for r in args.roles) + ', checked with codex_roles.py handshake)')
    elif args.command == 'install':
        install(args.project, args.check, args.factory)
    elif args.command == 'factory-off':
        path, updated = factory_config(args.project, False)
        changed = write_factory_config(path, updated)
        print(('Removed' if changed else 'No') + ' SDLC project factory instructions in ' + str(path) + '; start a fresh Codex session.')
    else:
        names = set()
        for name, data in definitions():
            names.add(name)
            target = ADAPTER / 'agents' / (name + '.toml')
            text = dumps(data)
            if args.check:
                if not target.exists() or target.read_text() != text:
                    raise ValueError('generated agent drift: ' + str(target))
            else:
                target.write_text(text)
        # install copies every *.toml, so a profile no definition produces must not linger.
        for orphan in sorted((ADAPTER / 'agents').glob('sdlc-*.toml')):
            if orphan.stem not in names:
                if args.check:
                    raise ValueError('generated agent drift: orphan ' + str(orphan))
                orphan.unlink()
        print('Codex agent definitions verified' if args.check else 'Codex agent definitions generated')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, KeyError) as exc:
        print(str(exc), file=sys.stderr)
        sys.exit(2)
