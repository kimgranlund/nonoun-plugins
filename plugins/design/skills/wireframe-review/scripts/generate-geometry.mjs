#!/usr/bin/env node
// Generates assets/foundation/maison/geometry.{json,css} from ui-geometry (derive.mjs --json).
// This file holds derive inputs only (n per cell, density); every length comes from a derive row.
//   node scripts/generate-geometry.mjs            regenerate
//   node scripts/generate-geometry.mjs --check    fail when the committed files differ
//   --density compact|default|loose               override the density dial (with --check: a negative control)
import fs from 'node:fs';import path from 'node:path';import assert from 'node:assert/strict';import {spawnSync} from 'node:child_process';
const root=path.resolve(import.meta.dirname,'..'),derivePath=path.resolve(root,'../ui-geometry/scripts/derive.mjs');
const usage='Usage: generate-geometry.mjs [--check] [--density compact|default|loose]';
const args=process.argv.slice(2),check=args.includes('--check'),rest=args.filter(a=>a!=='--check');
const dials={
  preset:'massimo',
  density:'default',
  // Scope font size n per tier: [n at md/md, px per scale step, px per size step]. Every n stays at or above the preset's 12px minimum.
  tiers:{widget:[13,0.5,0.5],product:[14,1,1],content:[16,1,2],brand:[20,2,2]},
};
if(rest.length===2&&rest[0]==='--density')dials.density=rest[1];else if(rest.length)throw Error(usage);
const steps=['sm','md','lg'],ix={sm:-1,md:0,lg:1};
// Cell property -> [tier, group, symbol] of a derive row. Names are the ones consumer CSS reads as --m-cell-*-<property> and --g-<property>.
const rows={
  height:['controls','control','h'], margin:['controls','control','I'], 'slot-height':['controls','control','S'],
  text:['unit','scale','F'], icon:['controls','icon','a.md'],
  'caption-text':['unit','type','body-sm'], 'small-control-text':['unit','type','label'],
  'chip-height':['controls','control','h_o'], 'compact-height':['controls','control','h_o'], 'chip-margin':['controls','control','m_c'],
  'chip-text':['unit','type','body-sm'],
  'listbox-margin':['collections','frame','d_c'], 'listbox-gutter':['controls','control','g_c'],
  'field-gutter':['containers','gap','label → control, control → help'], glyph:['controls','icon','a.sm'], 'radio-dot':['controls','mark','radio dot'],
  'body-text':['unit','type','body-md'], 'title-text':['unit','type','title-lg'],
  'heading-text':['unit','type','heading-md'], 'display-text':['unit','type','display-sm'],
  'subhead-text':['unit','type','heading-sm'], 'section-kicker-text':['unit','type','kicker-lg'],
  'group-kicker-text':['unit','type','kicker-md'],
};
const cache=new Map();
function derive(n){
  const key=String(n);if(cache.has(key))return cache.get(key);
  const r=spawnSync(process.execPath,[derivePath,'--n',key,'--density',dials.density,'--preset',dials.preset,'--json'],{encoding:'utf8'});
  if(r.error||r.status!==0||r.stderr.trim())throw Error('derive.mjs failed at n='+n+': '+(r.error?.message||r.stderr||r.stdout));
  const table=JSON.parse(r.stdout);cache.set(key,table);return table;
}
const px=(table,[tier,group,symbol],where)=>{const hit=table.filter(r=>r.tier===tier&&r.group===group&&r.symbol===symbol);if(hit.length!==1||!Number.isFinite(hit[0].px))throw Error('Missing derive row '+[tier,group,symbol].join('/')+' for '+where);return hit[0].px;};
function cell(n,where){
  const t=derive(n),out={};
  for(const [property,row] of Object.entries(rows))out[property]=px(t,row,where);
  out['icon-height-ratio']=out.icon/out.height;
  return out;
}
const profile={schemaVersion:3,source:'ui-geometry/scripts/derive.mjs --json',dials,defaultTier:'product',tiers:{}};
for(const [tier,[base,scaleStep,sizeStep]] of Object.entries(dials.tiers)){
  profile.tiers[tier]={};
  for(const scale of steps)for(const size of steps){const n=base+scaleStep*ix[scale]+sizeStep*ix[size];profile.tiers[tier][`${scale}/${size}`]={n,...cell(n,`${tier} ${scale}/${size}`)};}
}
const properties=Object.keys(profile.tiers.product['md/md']).filter(p=>p!=='n');
const value=(property,number)=>`${number}${property.endsWith('ratio')?'':'px'}`;
const cells=tier=>steps.flatMap(scale=>steps.flatMap(size=>properties.map(property=>{
  const number=profile.tiers[tier][`${scale}/${size}`][property];
  assert(Number.isFinite(number)&&number>0,`${tier}/${scale}/${size}/${property}`);
  return `  --m-cell-${scale}-${size}-${property}: ${value(property,number)};`;
}))).join('\n');
const lines=['/* Generated by scripts/generate-geometry.mjs from ui-geometry/scripts/derive.mjs --json. */','@layer maison.tokens {',':where(:root) { --corner-scale:1; --corner-shape:round; }',':where(:root) {'];
for(const axis of ['scale','size'])for(const step of steps)lines.push(`  --m-${axis}-${step}: ${step==='md'?1:0};`);
lines.push(cells(profile.defaultTier),'}');
for(const tier of Object.keys(profile.tiers))lines.push(`:where([data-tier="${tier}"]) {`,cells(tier),'}');
for(const axis of ['scale','size'])for(const step of steps){
  lines.push(`:where([data-${axis}="${step}"]) {`);
  for(const choice of steps)lines.push(`  --m-${axis}-${choice}: ${choice===step?1:0};`);
  lines.push('}');
}
lines.push(':where(*, :host) {');
for(const property of properties){
  const terms=steps.flatMap(scale=>steps.map(size=>`var(--m-cell-${scale}-${size}-${property}) * var(--m-scale-${scale}, ${scale==='md'?1:0}) * var(--m-size-${size}, ${size==='md'?1:0})`));
  lines.push(`  --g-${property==='margin'?'unit':property}: calc(${terms.join(' + ')});`);
}
// --g-unit is the inset I and --g-slot-height the slot S, so --g-height = S + 2I = h at density factor 1.
// The multipliers below are the documented consumer CSS inputs (--*-ratio, --*-amount) and role ladders
// (tile/card/section margins 2/3/4 d), kept from the earlier template so consumer CSS keeps working; they are not derive lengths.
lines.push(...`
  --g-d:calc(var(--g-unit) * var(--density-factor,1));
  --g-margin:var(--g-d);
  --g-control-margin:var(--g-d);
  --g-media:var(--g-slot-height);
  --g-height:calc(var(--g-slot-height) + 2 * var(--g-control-margin));
  --g-wrapper-padding:calc(var(--g-unit) * var(--control-gutter-ratio,.25));
  --g-label-padding:calc(var(--g-unit) / 2);
  --g-wrapper-gap:0px;
  --g-slot-gap:calc(var(--g-control-margin) / 2);
  --g-gutter:var(--g-d);
  --g-page-gutter:calc(4 * var(--g-d) * var(--page-gutter-ratio,1));
  --g-group-gutter:calc(var(--g-margin-reference,var(--g-d)) * var(--group-gutter-ratio,.5));
  --r-control:calc(var(--g-height) / 2 * var(--control-radius-amount,0));
  --r-mark:0px;
  --r-margin:var(--r-control);
  --r-listbox:var(--r-control);
  --r-listbox-option:max(calc(var(--g-slot-height) / 2 * var(--control-radius-amount,0)),calc(var(--r-listbox) * var(--control-radius-retained,0)));
  --r-group:0px;
  --r-group-inner:0px;
  --r-widget:var(--r-tile);
  --r-layout:var(--r-section);
`.trim().split('\n'));
for(const [name,m] of [['tile',2],['card',3],['section',4]])lines.push(`  --g-${name}-margin:calc(${m} * var(--g-d));`,`  --g-${name}-gutter:calc(var(--g-${name}-margin) * var(--container-gutter-ratio,.75));`,`  --r-${name}:calc(var(--g-${name}-margin) * var(--container-radius-amount,0));`);
lines.push('  --g-table-cell-margin:calc(var(--g-control-margin) + var(--g-wrapper-padding));','  --g-table-clearance:var(--g-control-margin);','  --g-table-row-height:var(--g-height);','  --g-table-column-gap:calc(var(--g-control-margin) / 2);');
// Read aliases keep existing consumer CSS working; author with margin/gutter.
lines.push('  /* Deprecated read aliases; do not author new styles with these names. */');
for(const [oldName,newName] of [['--g-inset','--g-margin'],['--g-chip-inset','--g-chip-margin'],['--r-inset','--r-margin']])lines.push(`  ${oldName}: var(${newName});`);
for(const scale of steps)for(const size of steps)for(const prefix of ['','chip-'])lines.push(`  --m-cell-${scale}-${size}-${prefix}inset: var(--m-cell-${scale}-${size}-${prefix}margin);`);
lines.push('}');
for(const [name,factor] of Object.entries({tight:.5,compact:.75,regular:1,spacious:1.25,loose:1.5}))lines.push(`[data-density=${name}] { --density-factor:${factor}; }`);
lines.push('}','');
const outputs={'assets/foundation/maison/geometry.json':JSON.stringify(profile,null,2)+'\n','assets/foundation/maison/geometry.css':lines.join('\n')};
for(const [file,text] of Object.entries(outputs)){
  const target=path.join(root,file);
  if(check){if(fs.readFileSync(target,'utf8')!==text){console.error('Stale '+file+'; run node scripts/generate-geometry.mjs');process.exitCode=1;}}
  else fs.writeFileSync(target,text);
}
if(!process.exitCode)console.log((check?'Verified':'Generated')+' geometry from ui-geometry derive.mjs at density '+dials.density);
