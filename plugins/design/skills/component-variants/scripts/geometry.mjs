// Review-shell geometry custom properties, derived at build time from the sibling ui-geometry skill.
// Every value comes from `derive.mjs --json`; nothing here is a hand-typed length.
import path from 'node:path';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
import {pathToFileURL} from 'node:url';
const root=path.resolve(import.meta.dirname,'..');
export const derivePath=path.resolve(root,'../ui-geometry/scripts/derive.mjs');
// Pinned dials: root text n, density, control curvature and card curvature/depth.
export const dials={n:14,density:'default',kappa:0.75,kappaCard:0.5,card:4};
// Token -> [tier, symbol] in the derive output.
export const tokens={
  '--g-text':['unit','F'],
  '--g-caption-text':['unit','body-sm'],
  '--g-height':['controls','h'],
  '--g-inset':['controls','I'],
  '--g-icon':['controls','a.md'],
  '--m-border-thin':['unit','b'],
  '--m-focus-ring-width':['controls','ring width w'],
  '--r-control':['controls',`r  κ=${dials.kappa}`],
  '--r-card':['containers',`R card-3  κ=${dials.kappaCard}`],
  '--m-gap-stack':['containers',`groups in card-${dials.card}`],
  '--m-gap-stack-loose':['layout','M'],
  '--m-gap-grid':['layout','card'],
  '--m-inset-panel':['containers','panel inset'],
  '--m-inset-page':['containers','page inset'],
};
export function derive(){
  if(!fs.existsSync(derivePath))throw Error('Missing ui-geometry beside component-variants: '+derivePath);
  const args=['--json','--n',dials.n,'--density',dials.density,'--kappa',dials.kappa,'--kappa-card',dials.kappaCard,'--card',dials.card].map(String);
  const run=spawnSync(process.execPath,[derivePath,...args],{encoding:'utf8'});
  if(run.status!==0)throw Error('ui-geometry derive failed: '+(run.stderr||run.error?.message));
  return JSON.parse(run.stdout);
}
export function geometryCSS(rows=derive()){
  const lines=Object.entries(tokens).map(([name,[tier,symbol]])=>{
    const row=rows.find(r=>r.tier===tier&&r.symbol===symbol);
    if(!row||!Number.isFinite(row.px))throw Error(`ui-geometry derive has no ${tier} "${symbol}" for ${name}`);
    return `  ${name}: ${row.px}px; /* ${tier} ${symbol} = ${row.expr} */`;
  });
  const d=Object.entries(dials).map(([k,v])=>k+' '+v).join(', ');
  return `/* Generated by component-variants/scripts/geometry.mjs from ui-geometry derive.mjs (${d}). */\n:root {\n${lines.join('\n')}\n}\n`;
}
if(import.meta.url===pathToFileURL(process.argv[1]).href)process.stdout.write(geometryCSS());
