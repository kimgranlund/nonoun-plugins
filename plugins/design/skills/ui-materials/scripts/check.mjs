#!/usr/bin/env node
// ui-materials checks: the vocabulary and closed sets in references/terms.json against everything that copies or uses them,
// then a negative control per check (a mutated copy that must fail). Node built-ins only; reads no network and runs no
// project code. Exit 0 when every check passes and every control bites; 1 otherwise.
//
//   node scripts/check.mjs
//
// Sibling skills are read when installed beside this one (../ui-colors, ../ui-geometry, ../ui-showcase-bento: each one's
// references/terms.json, ui-geometry's SKILL.md and ui-showcase-bento's sources/ui-materials.json); a check that needs a
// missing sibling says "skipped" and does not count as a pass. The `request` check also runs two sibling scripts:
// ui-geometry's derive.mjs (cast alphas) and ui-colors' system.mjs (one colour system, in a temporary directory).

import { readFileSync, readdirSync, existsSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fragment, castAlphas } from './request.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS = resolve(ROOT, '..');
const read = (p) => readFileSync(p, 'utf8');
const readJson = (p) => JSON.parse(read(p));
const clone = (x) => JSON.parse(JSON.stringify(x));

function load() {
  const docs = { 'SKILL.md': read(join(ROOT, 'SKILL.md')) };
  for (const f of readdirSync(join(ROOT, 'references')).filter((f) => f.endsWith('.md')).sort()) docs['references/' + f] = read(join(ROOT, 'references', f));
  const opt = (p, f) => (existsSync(p) ? f(p) : null);
  // The paint roles, ui-geometry's cast alphas for them, and one colour system generated by ui-colors from the request
  // fragment (null when a sibling is missing; { error } when ui-colors refuses the request).
  const paint = readJson(join(ROOT, 'references', 'paint.json')), casts = castAlphas(paint);
  const system = join(SKILLS, 'ui-colors', 'scripts', 'system.mjs');
  let paintRun = null;
  if (casts && existsSync(system)) {
    const dir = mkdtempSync(join(tmpdir(), 'ui-materials-check-')), rq = join(dir, 'request.json');
    try {
      writeFileSync(rq, JSON.stringify({ tonal: false, series: false, alpha: false, dtcg: false, ...fragment(paint, casts) }));
      execFileSync(process.execPath, [system, '--request', rq, '--out', join(dir, 'out')], { stdio: ['ignore', 'pipe', 'pipe'] });
      paintRun = readJson(join(dir, 'out', 'system.json'));
    } catch (e) { paintRun = { error: String((e.stderr && e.stderr.toString()) || e.message).trim().slice(0, 200) }; }
    rmSync(dir, { recursive: true, force: true });
  }
  const walk = (rel = '') => readdirSync(join(ROOT, rel), { withFileTypes: true }).flatMap((e) =>
    e.name.startsWith('.') ? [] : e.isDirectory() ? walk(join(rel, e.name)) : [[join(rel, e.name), read(join(ROOT, rel, e.name))]]);
  return {
    docs, paint, casts, paintRun, files: walk(),
    terms: readJson(join(ROOT, 'references', 'terms.json')),
    colors: opt(join(SKILLS, 'ui-colors', 'references', 'terms.json'), readJson),
    geometry: opt(join(SKILLS, 'ui-geometry', 'SKILL.md'), read),
    geometryTerms: opt(join(SKILLS, 'ui-geometry', 'references', 'terms.json'), readJson),
    bentoTerms: opt(join(SKILLS, 'ui-showcase-bento', 'references', 'terms.json'), readJson),
    bento: opt(join(SKILLS, 'ui-showcase-bento', 'sources', 'ui-materials.json'), readJson),
  };
}

// ---------------------------------------------------------------- helpers
const SIBLINGS = /ui-colors|ui-geometry|ui-showcase-bento|instrumental-modernism|Instrumental Modernism|Apple|Material Design/;
// Prose only: fenced blocks and inline code removed, split into paragraphs (blank-line separated, table rows one each).
function prose(text) {
  const noFences = text.replace(/^---[\s\S]*?\n---\n/, '').replace(/```[\s\S]*?```/g, '');
  const paras = [];
  for (const block of noFences.split(/\n\s*\n/)) {
    const lines = block.split('\n');
    if (lines.every((l) => l.trim().startsWith('|'))) lines.forEach((l) => paras.push(l)); else paras.push(block);
  }
  return paras.map((p) => p.replace(/`[^`]*`/g, ' ').replace(/\]\([^)]*\)/g, ']'));
}
const lineOf = (text, idx) => text.slice(0, idx).split('\n').length;
const normRole = (r) => r.replace(/-\d+$/, '-<n>');
function colorRoles(colors) {
  const R = colors.roles, set = new Set(Object.keys(R.page));
  for (const s of R.scaleRoles) for (const suf of Object.keys(R.scaleSuffixes)) set.add(s + suf);
  return set;
}
function codeBlocksAfter(text, heading) {
  const at = text.indexOf(heading); if (at < 0) return [];
  const next = text.indexOf('\n## ', at + heading.length);
  const section = text.slice(at, next < 0 ? undefined : next);
  return [...section.matchAll(/```[a-z]*\n([\s\S]*?)```/g)].map((m) => m[1]);
}

// ---------------------------------------------------------------- checks (each returns a list of findings)
const CHECKS = {
  terms(c) {
    const f = [], T = c.terms, ids = new Set();
    for (const p of T.principles || []) if (!p.id || !p.rule || !p.why) f.push(`principle ${p.id || '?'} lacks id, rule or why`);
    for (const k of T.concepts || []) {
      if (ids.has(k.id)) f.push(`duplicate concept ${k.id}`); ids.add(k.id);
      for (const key of ['id', 'term', 'group', 'definition', 'intent']) if (!k[key]) f.push(`concept ${k.id || '?'} lacks ${key}`);
      for (const key of ['aliases', 'avoid', 'names', 'related']) if (k[key] && !Array.isArray(k[key])) f.push(`concept ${k.id} › ${key} is not a list`);
    }
    for (const k of T.concepts || []) for (const r of k.related || []) if (!ids.has(r)) f.push(`concept ${k.id} relates to unknown ${r}`);
    const S = T.sets, settings = S.settings;
    for (const [name, p] of Object.entries(S.presets)) {
      if (Object.keys(p).sort().join() !== Object.keys(settings).sort().join()) f.push(`preset ${name} does not set exactly the four settings`);
      for (const [k, v] of Object.entries(p)) if (!(settings[k] || []).includes(v)) f.push(`preset ${name} uses undeclared ${k}: ${v}`);
    }
    for (const [k, vals] of Object.entries(settings)) if (JSON.stringify(S.attributes['data-' + k]) !== JSON.stringify(vals)) f.push(`attribute data-${k} differs from setting ${k}`);
    if (JSON.stringify(S.attributes['data-material']) !== JSON.stringify(Object.keys(S.presets))) f.push('attribute data-material differs from the preset names');
    for (const [t, d] of Object.entries(T.tokens)) for (const w of d.writes || []) if (!S.passes.includes(w)) f.push(`token ${t} written by unknown pass ${w}`);
    for (const [i, d] of Object.entries(T.inputs)) if (!d.uiColors) f.push(`input ${i} has no ui-colors default`);
    return f;
  },

  // SKILL.md's two contract blocks equal the catalogue: material tokens, then palette inputs with their defaults.
  contract(c) {
    const f = [], [tokBlock, inBlock] = codeBlocksAfter(c.docs['SKILL.md'], '## The token contract');
    if (!tokBlock || !inBlock) return ['SKILL.md › The token contract lacks its two blocks (tokens, inputs)'];
    const listed = new Set(tokBlock.match(/--[a-z][a-z0-9-]*(?:<n>)?/g));
    const cat = new Set(Object.keys(c.terms.tokens));
    for (const t of listed) if (!cat.has(t)) f.push(`SKILL.md contract lists ${t}, which terms.json › tokens lacks`);
    for (const t of cat) if (!listed.has(t)) f.push(`terms.json › tokens has ${t}, which the SKILL.md contract does not list`);
    const pairs = Object.fromEntries([...inBlock.matchAll(/(--[a-z][a-z0-9-]*)\s*→\s*([a-z][a-z0-9-]*)/g)].map((m) => [m[1], m[2]]));
    for (const [i, d] of Object.entries(c.terms.inputs)) {
      if (!(i in pairs)) f.push(`SKILL.md inputs block lacks ${i}`);
      else if (pairs[i] !== d.uiColors) f.push(`SKILL.md maps ${i} → ${pairs[i]}, terms.json → ${d.uiColors}`);
    }
    for (const i of Object.keys(pairs)) if (!(i in c.terms.inputs)) f.push(`SKILL.md inputs block lists ${i}, which terms.json › inputs lacks`);
    return f;
  },

  // Every custom property any doc names is a declared token or input, or a ui-colors role (--colors-*).
  closure(c) {
    const f = [], known = new Set([...Object.keys(c.terms.tokens), ...Object.keys(c.terms.inputs)]);
    const roles = c.colors ? colorRoles(c.colors) : null;
    for (const [doc, text] of Object.entries(c.docs)) for (const m of text.matchAll(/--[a-z][a-z0-9-]*/g)) {
      const t = m[0]; if (t.endsWith('-')) continue;                       // a pattern such as --colors-<role>
      if (t.startsWith('--colors-paint-')) continue;                       // a paint role: the `paint` check holds these
      const n = t.replace(/-\d+$/, '-<n>');
      if (t.startsWith('--colors-')) { if (roles && !roles.has(normRole(t.slice(9)))) f.push(`${doc}:${lineOf(text, m.index)} ${t} is not a ui-colors role`); continue; }
      if (!known.has(t) && !known.has(n)) f.push(`${doc}:${lineOf(text, m.index)} ${t} is neither a material token nor a palette input`);
    }
    return [...new Set(f)];
  },

  // Every input and mark default names a role ui-colors emits. A role ui-colors emits only with `neutrals`
  // (its roles.splitOnly) needs a fallback that every system emits, written into fills.md's base block.
  inputs(c) {
    if (!c.colors) return null;
    const f = [], roles = colorRoles(c.colors), split = new Set(c.colors.roles.splitOnly || []);
    const block = codeBlocksAfter(c.docs['references/fills.md'], '## Base block')[0] || '';
    for (const [i, d] of Object.entries(c.terms.inputs)) {
      if (!roles.has(normRole(d.uiColors))) { f.push(`input ${i} defaults to ${d.uiColors}, which ui-colors does not emit`); continue; }
      if (split.has(d.uiColors)) {
        if (!d.fallback) { f.push(`input ${i} defaults to ${d.uiColors}, which ui-colors emits only with neutrals, and names no fallback`); continue; }
        // A fallback may be another input (written `--name`), which carries its own fallback and scheme choice.
        if (d.fallback.startsWith('--')) { if (!(d.fallback in c.terms.inputs) || d.fallback === i) { f.push(`input ${i} falls back to ${d.fallback}, which is not another declared input`); continue; } }
        else if (!roles.has(normRole(d.fallback)) || split.has(d.fallback)) { f.push(`input ${i} falls back to ${d.fallback}, which a default ui-colors system does not emit`); continue; }
      }
      // A `dark` role is what the input reads in the dark scheme, chosen by light-dark(); every system must emit it.
      if (d.dark != null && (!roles.has(normRole(d.dark)) || split.has(d.dark))) { f.push(`input ${i} reads ${d.dark} in the dark scheme, which a default ui-colors system does not emit`); continue; }
      const light = d.fallback ? `var(--colors-${d.uiColors}, var(${d.fallback.startsWith('--') ? d.fallback : '--colors-' + d.fallback}))` : `var(--colors-${d.uiColors})`;
      const value = d.dark != null ? `light-dark(${light}, var(--colors-${d.dark}))` : light;
      if (!block.includes(`${i}: ${value};`)) f.push(`fills.md base block does not set ${i} to ${value}`);
    }
    for (const [t, r] of Object.entries(c.terms.markDefaults || {})) {
      if (!roles.has(normRole(r))) f.push(`token ${t} defaults to ${r}, which ui-colors does not emit`);
      else if (split.has(r)) f.push(`token ${t} defaults to ${r}, which ui-colors emits only with neutrals`);
    }
    return f;
  },

  // fills.md's base block gives every fills-written token and every input a value.
  fills(c) {
    const f = [], block = codeBlocksAfter(c.docs['references/fills.md'], '## Base block')[0] || '';
    const defined = new Set([...block.matchAll(/(--[a-z][a-z0-9-]*)\s*:/g)].map((m) => m[1].replace(/^--data-\d+$/, '--data-<n>')));
    for (const [t, d] of Object.entries(c.terms.tokens)) if ((d.writes || []).includes('fills') && !defined.has(t)) f.push(`fills.md base block does not define ${t}`);
    for (const i of Object.keys(c.terms.inputs)) if (!defined.has(i)) f.push(`fills.md base block does not define input ${i}`);
    return f;
  },

  // An alias never names another concept, a preset, a setting value or a word a sibling owns.
  aliases(c) {
    const f = [], T = c.terms, taken = new Map();
    for (const k of T.concepts) taken.set(k.term.toLowerCase(), `the concept ${k.term}`);
    for (const p of Object.keys(T.sets.presets)) taken.set(p, `the ${p} preset`);
    for (const vals of Object.values(T.sets.settings)) for (const v of vals) if (!taken.has(v)) taken.set(v, `the setting value ${v}`);
    for (const w of T.foreign || []) taken.set(w.word.toLowerCase(), `${w.owner}'s word`);
    for (const k of T.concepts) for (const a of k.aliases || []) {
      const hit = taken.get(a.toLowerCase());
      if (hit && a.toLowerCase() !== k.term.toLowerCase()) f.push(`concept ${k.id}: alias "${a}" is ${hit}`);
    }
    return f;
  },

  // Every word listed as a sibling's is a concept, or an alias of one, in that sibling's own vocabulary.
  foreign(c) {
    const files = { 'ui-colors': c.colors, 'ui-geometry': c.geometryTerms, 'ui-showcase-bento': c.bentoTerms };
    if (Object.values(files).some((v) => !v)) return null;
    const label = (s) => s.toLowerCase().replace(/\s*\(.*\)\s*$/, '').trim(), f = [];
    for (const w of c.terms.foreign || []) {
      const T = files[w.owner];
      if (!T) { f.push(`foreign word "${w.word}" names ${w.owner}, which is not a sibling skill`); continue; }
      const known = new Set(T.concepts.flatMap((k) => [k.id, label(k.term), ...(k.aliases || []).map(label)]));
      if (!known.has(w.word.toLowerCase())) f.push(`foreign word "${w.word}" is not a concept or alias in ${w.owner}'s terms.json`);
    }
    return f;
  },

  // lighting.md's numbered paint passes equal terms.json › sets.paintPasses, in order.
  paintPasses(c) {
    const text = c.docs['references/lighting.md'], at = text.indexOf('## The paint passes');
    const next = text.indexOf('\n## ', at + 1);
    const got = at < 0 ? [] : [...text.slice(at, next < 0 ? undefined : next).matchAll(/^\d+\. \*\*([^*]+)\*\*/gm)].map((m) => m[1].toLowerCase());
    const want = c.terms.sets.paintPasses || [];
    return JSON.stringify(got) === JSON.stringify(want) ? [] : [`lighting.md lists the paint passes [${got.join(', ')}]; terms.json › sets.paintPasses says [${want.join(', ')}]`];
  },

  // A canvas size belongs to the brief it comes from and to ui-showcase-bento: no doc here repeats one.
  canvas(c) {
    const f = [];
    for (const [doc, text] of Object.entries(c.docs)) for (const m of text.matchAll(/\b\d{3,4} × \d{3,4}\b/g)) f.push(`${doc}:${lineOf(text, m.index)} "${m[0]}": cite the brief instead of copying its canvas size`);
    return f;
  },

  // Every paint role a doc names is declared in paint.json, every declared role is used by a doc, and each is well formed.
  paint(c) {
    const f = [], P = c.paint, roles = P.roles, used = new Set(); let castPattern = false;
    for (const [doc, text] of Object.entries(c.docs)) for (const m of text.matchAll(/--colors-paint-[a-z0-9<>-]+/g)) {
      if (m[0].includes('<')) { if (m[0].startsWith('--colors-paint-cast-<')) castPattern = true; continue; }
      const name = m[0].slice('--colors-paint-'.length).replace(/-$/, ''); used.add(name);
      if (!(name in roles)) f.push(`${doc}:${lineOf(text, m.index)} --colors-paint-${name} is not a role in paint.json`);
    }
    for (const [name, r] of Object.entries(roles)) {
      if (!/^[a-z][a-z0-9-]*$/.test(name)) f.push(`paint.json: role name ${name} is not lowercase letters, digits and hyphens`);
      if (!P.bases[r.base]) f.push(`paint.json: role ${name} names the unknown base ${r.base}`);
      if (!r.for) f.push(`paint.json: role ${name} does not say what it is for`);
      if (r.cast != null) {
        if (r.alpha != null || r.darkAlpha != null) f.push(`paint.json: cast role ${name} states an alpha; cast alphas are ui-geometry's`);
        if (!castPattern && !used.has(name)) f.push(`paint.json: cast role ${name} is declared, but no doc paints with --colors-paint-cast-<k>`);
        continue;
      }
      for (const k of ['alpha', 'darkAlpha']) if ((k === 'alpha' || r[k] != null) && !(typeof r[k] === 'number' && r[k] >= 0 && r[k] <= 1)) f.push(`paint.json: role ${name}.${k} is not a number from 0 to 1`);
      if (!used.has(name)) f.push(`paint.json: role ${name} is declared, but no doc paints with it`);
    }
    // A glass face is the raised face at an alpha, so its base follows the --element input in both schemes.
    const el = c.terms.inputs['--element'], face = P.bases.face || {};
    if (JSON.stringify([].concat(face.of)) !== JSON.stringify([el.uiColors, el.fallback].filter(Boolean)) || (face.darkOf ?? null) !== (el.dark ?? null)) f.push('paint.json › bases.face does not follow the --element input (its default, fallback and dark-scheme role)');
    const casts = Object.values(roles).filter((r) => r.cast != null).map((r) => r.cast).sort((a, b) => a - b);
    if (JSON.stringify(casts) !== JSON.stringify([...Array(P.cast.layers)].map((_, i) => i + 1))) f.push(`paint.json: cast roles [${casts.join(', ')}] do not match cast.layers ${P.cast.layers}`);
    return f;
  },

  // No doc prescribes a colour the browser derives: every such colour is a paint role that ui-colors generates.
  derived(c) {
    const f = [], re = /color-mix\(\s*in\b|\bcalc\(\s*[^)\s]|\bfrom\s+var\(|\b(?:oklch|oklab|rgb|hsl|color)\(\s*from\b/g;
    for (const [doc, text] of Object.entries(c.docs)) for (const m of text.matchAll(re)) f.push(`${doc}:${lineOf(text, m.index)} "${m[0]}": a derived colour; paint with a role from paint.json`);
    return f;
  },

  // scripts/request.mjs turns paint.json into a request ui-colors accepts, and the generated system holds every paint role
  // in every mode at the alpha paint.json asks for that mode's scheme (a cast role: ui-geometry's alpha for its layer).
  request(c) {
    if (!c.paintRun) return null;
    if (c.paintRun.error) return [`ui-colors refused the request from request.mjs: ${c.paintRun.error}`];
    const f = [], frag = fragment(c.paint, c.casts).translucent, num = (s) => s.match(/-?[\d.]+/g).map(Number);
    for (const name of Object.keys(c.paint.roles)) if (!(c.paint.prefix + name in frag)) f.push(`request.mjs leaves out the paint role ${name}`);
    for (const [id, M] of Object.entries(c.paintRun.modes)) for (const [name, e] of Object.entries(frag)) {
      const got = M.variables['--colors-' + name], want = M.scheme === 'dark' && e.darkAlpha != null ? e.darkAlpha : e.alpha;
      if (!got) { f.push(`${id}: the generated system lacks --colors-${name}`); continue; }
      const n = num(got), alpha = n.length > 3 ? n[3] : 1;
      if (Math.abs(alpha - want) > 5e-4 + 1e-9) f.push(`${id}: --colors-${name} has alpha ${alpha}, paint.json asks ${want}`);
    }
    return f;
  },

  // Contrast floors are ui-colors' APCA thresholds: no doc or term here states a contrast ratio or a WCAG criterion number.
  ratios(c) {
    const f = [], re = /(?<![\d.])\d+(?:\.\d+)?:1\b|\b1\.4\.11\b/g;
    for (const [doc, text] of Object.entries(c.docs)) for (const m of text.matchAll(re)) f.push(`${doc}:${lineOf(text, m.index)} "${m[0]}": cite ui-colors' APCA threshold (apca.ui), not a ratio`);
    for (const m of JSON.stringify(c.terms).matchAll(re)) f.push(`references/terms.json "${m[0]}": cite ui-colors' APCA threshold (apca.ui), not a ratio`);
    return f;
  },

  // SKILL.md's transmission invariant names every scheme constant in the reach.
  reachRow(c) {
    const row = (c.docs['SKILL.md'].match(/^\| Transmission writes only[^\n]*$/m) || [''])[0];
    if (!row) return ['SKILL.md has no "Transmission writes only" invariant'];
    return c.terms.transmissionReach.filter((t) => (c.terms.tokens[t] || {}).scheme && !row.includes(t)).map((t) => `SKILL.md's transmission invariant does not name ${t}, which transmissionReach lists`);
  },

  // Transmission writes only its reach, and the reach lists only what transmission writes.
  reach(c) {
    const f = [], reach = new Set(c.terms.transmissionReach);
    const writes = Object.entries(c.terms.tokens).filter(([, d]) => (d.writes || []).includes('transmission')).map(([t]) => t);
    for (const t of writes) if (!reach.has(t)) f.push(`transmission writes ${t}, outside its reach`);
    for (const t of reach) if (!writes.includes(t)) f.push(`transmissionReach lists ${t}, which transmission does not write`);
    return f;
  },

  // Every copy of the presets equals terms.json: composition.md's PRESETS and SKILL.md's preset table.
  presets(c) {
    const f = [], want = c.terms.sets.presets, keys = ['lighting', 'transmission', 'delineation', 'chroma'];
    const comp = {}; for (const m of c.docs['references/composition.md'].matchAll(/^\s*(\w+):\s*\{([^}]*)\}/gm)) comp[m[1]] = Object.fromEntries([...m[2].matchAll(/(\w+):\s*'(\w+)'/g)].map((x) => [x[1], x[2]]));
    const table = {}; for (const m of c.docs['SKILL.md'].matchAll(/^\| \*\*([\w ]+)\*\*(?: \(`(\w+)`\))? \| (\w+) \| (\w+) \| (\w+) \| (\w+) \|$/gm)) table[m[2] || m[1].toLowerCase()] = { lighting: m[3], transmission: m[4], delineation: m[5], chroma: m[6] };   // a display name may carry its id: **Frosted glass** (`frosted`)
    for (const [where, got] of [['composition.md PRESETS', comp], ['SKILL.md preset table', table]]) {
      for (const name of Object.keys(want)) { if (!got[name]) { f.push(`${where} lacks ${name}`); continue; }
        for (const k of keys) if (got[name][k] !== want[name][k]) f.push(`${where} › ${name}.${k} is ${got[name][k]}, terms.json says ${want[name][k]}`); }
      for (const name of Object.keys(got)) if (!want[name]) f.push(`${where} has ${name}, which terms.json › presets lacks`);
    }
    return f;
  },

  // Attribute selectors in code blocks name declared attributes and values, and a setting is never matched by presence
  // alone (prose may name the trap; code may not use it).
  selectors(c) {
    const f = [], A = c.terms.sets.attributes;
    for (const [doc, full] of Object.entries(c.docs)) {
      const text = full.replace(/```[\s\S]*?```|[^`]+/g, (s) => (s.startsWith('```') ? s : s.replace(/[^\n]/g, ' ')));
      for (const m of text.matchAll(/\[(data-[a-z-]+)="([^"]+)"\]/g)) {
        if (!(m[1] in A)) { if (/^data-(layer|relief|face|material|lighting|transmission|delineation|chroma|lens)$/.test(m[1])) f.push(`${doc}:${lineOf(text, m.index)} ${m[1]} is not declared`); continue; }
        if (!A[m[1]].includes(m[2])) f.push(`${doc}:${lineOf(text, m.index)} [${m[1]}="${m[2]}"] uses an undeclared value`);
      }
      for (const m of text.matchAll(/\[data-(lighting|transmission|delineation|chroma)\](?!:not\()/g)) f.push(`${doc}:${lineOf(text, m.index)} [data-${m[1]}] matches every value, ${m[1] === 'transmission' ? 'opaque' : 'the plainest'} included; add :not(…)`);
    }
    return f;
  },

  // ui-showcase-bento's ui-materials source switches over the same sets.
  bento(c) {
    if (!c.bento) return null;
    const f = [], axis = (n) => (c.bento.axes || []).find((a) => a.name === n);
    const mat = axis('material'), anat = axis('anatomy');
    if (!mat || JSON.stringify(mat.values) !== JSON.stringify(Object.keys(c.terms.sets.presets))) f.push(`bento material axis ${JSON.stringify(mat && mat.values)} differs from the presets`);
    if (!anat || JSON.stringify(anat.values) !== JSON.stringify(c.terms.sets.anatomy)) f.push(`bento anatomy axis ${JSON.stringify(anat && anat.values)} differs from sets.anatomy`);
    return f;
  },

  // Every sentence in that source (acceptance, token commands, captions, note) keeps to this vocabulary, plurals included.
  bentoWords(c) {
    if (!c.bento) return null;
    const f = [], B = c.bento;
    const texts = [...(B.acceptance || []), ...((B.tokens || {}).commands || []), ...(B.axes || []).flatMap((a) => Object.values(a.captions || {})), B.note || ''];
    for (const a of texts) for (const k of c.terms.concepts) for (const w of k.avoid || [])
      if (!w.includes('(') && new RegExp(`\\b${w}s?\\b`, 'i').test(a)) f.push(`bento source uses "${w}", avoided for ${k.term}: ${a.slice(0, 60)}…`);
    return f;
  },

  // Elevation levels are ui-geometry's names, and no doc numbers them.
  levels(c) {
    const f = [];
    if (c.geometry) {
      const m = /elevation levels: ([a-z, ]+)\|/.exec(c.geometry);
      const names = m ? m[1].split(',').map((s) => s.trim()) : [];
      if (!names.length) f.push('ui-geometry SKILL.md no longer lists its elevation levels');
      for (const [part, lvl] of Object.entries(c.terms.sets.levels)) if (!names.includes(lvl)) f.push(`level for ${part} is ${lvl}, not one of ui-geometry's (${names.join(', ')})`);
    }
    for (const [doc, text] of Object.entries(c.docs)) for (const m of text.matchAll(/\blevel[- ][12]\b/gi)) f.push(`${doc}:${lineOf(text, m.index)} "${m[0]}": name ui-geometry's level instead`);
    return f;
  },

  // Words a sibling owns, and words avoided for a concept, stay out of prose (a paragraph naming the sibling is exempt).
  words(c) {
    const f = [];
    const banned = [/\bmodes?\b/i, /\bthemes?\b/i, /\brole tokens?\b/i, /\baccent\b/i, /\bpaint layers?\b/i, /\bsurfaces?\b/i, /\bplanes?\b/i, /\b(?:each|five|same) steps?\b/i, /\btheme constants?\b/i];
    for (const [doc, text] of Object.entries(c.docs)) for (const p of prose(text)) {
      if (SIBLINGS.test(p)) continue;
      for (const re of banned) { const m = re.exec(p); if (m) f.push(`${doc}: "${m[0]}" in "${p.trim().slice(0, 70)}…"`); }
    }
    return f;
  },

  // Rule docs carry no hedges.
  hedges(c) {
    const f = [], banned = /\b(a little|slightly|often|optionally|a few|small step|faint enough|probably|rarely|as needed|if appropriate)\b/i;
    for (const [doc, text] of Object.entries(c.docs)) for (const p of prose(text)) { const m = banned.exec(p); if (m) f.push(`${doc}: hedge "${m[0]}" in "${p.trim().slice(0, 70)}…"`); }
    return f;
  },

  // The routing surface: a description within the host's limit that names every nearest NOT-case.
  description(c) {
    const f = [], m = /^description: (.*)$/m.exec(c.docs['SKILL.md']);
    if (!m) return ['SKILL.md has no description'];
    if (m[1].length > 1024) f.push(`description is ${m[1].length} characters (limit 1024)`);
    if (/: | #/.test(m[1])) f.push('description holds ": " or " #", which ends a plain YAML scalar: a strict host refuses the file');
    for (const s of ['ui-colors', 'ui-geometry', 'ui-showcase-bento']) if (!m[1].includes(s)) f.push(`description does not name ${s} as a NOT-case`);
    return f;
  },

  // The entry: under 18,000 characters, every link resolves, every contents anchor names a heading.
  entry(c) {
    const f = [], text = c.docs['SKILL.md'];
    if (text.length >= 18000) f.push(`SKILL.md is ${text.length} characters (limit 18,000)`);
    for (const [doc, body] of Object.entries(c.docs)) for (const m of body.matchAll(/\]\(([^)#\s]+)(#[^)]+)?\)/g)) {
      if (/^https?:/.test(m[1])) continue;
      const base = doc.includes('/') ? join(ROOT, dirname(doc)) : ROOT;
      if (!existsSync(join(base, m[1]))) f.push(`${doc}: link ${m[1]} does not resolve`);
    }
    const slug = (h) => h.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-');
    const heads = new Set([...text.matchAll(/^#{2,3} (.+)$/gm)].map((m) => slug(m[1])));
    for (const m of text.matchAll(/\]\(#([^)]+)\)/g)) if (!heads.has(m[1])) f.push(`SKILL.md: anchor #${m[1]} names no heading`);
    return f;
  },
  // Host-project names, stored reversed so this file does not contain them.
  hostNames: (c) => {
    const names = ['omissam', 'nosiam'].map((w) => [...w].reverse().join(''));
    return c.files.flatMap(([path, text]) => names.filter((w) => text.toLowerCase().includes(w)).map(() => `${path}: names a host project`));
  },
};

