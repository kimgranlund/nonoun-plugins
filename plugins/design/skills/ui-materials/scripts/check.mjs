// ---------------------------------------------------------------- run
const base = load();
let passed = 0, failed = 0, skipped = 0, bit = 0, missed = 0;
for (const [name, check] of Object.entries(CHECKS)) {
  const out = check(base);
  if (out === null) { skipped++; console.log(`skip ${name}: its sibling skill is not installed beside this one`); continue; }
  if (out.length) { failed++; console.log(`FAIL ${name}`); for (const x of out) console.log(`     ${x}`); } else { passed++; console.log(`ok   ${name}`); }
}
for (const [name, mutates] of Object.entries(CONTROLS)) for (const [n, mutate] of [].concat(mutates).entries()) {
  if (base.bento === null && name === 'bento') continue;
  const c = mutate({ ...base, docs: { ...base.docs }, terms: clone(base.terms), paint: clone(base.paint), bento: base.bento && clone(base.bento) });
  const out = CHECKS[name](c), label = n ? `${name} (${n + 1})` : name;
  if (out === null) continue;
  if (out.length) { bit++; console.log(`ok   control ${label} fails as it must (${out[0].slice(0, 80)})`); } else { missed++; console.log(`FAIL control ${label}: the mutated copy passed`); }
}
const verdict = failed || missed ? 'FAILED' : 'passed';
console.log(`ui-materials check ${verdict}: ${passed} checks passed, ${failed} failed, ${skipped} skipped; ${bit} controls bit, ${missed} did not`);
process.exit(failed || missed ? 1 : 0);
