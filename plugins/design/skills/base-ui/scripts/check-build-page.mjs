import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
import {buildPage} from './build-page.mjs';
import {beginReview, verifyDelivery} from './review-delivery.mjs';
import {localAssets} from './lib/local-assets.mjs';
const [playwrightPath, executablePath] = process.argv.slice(2);
if (!playwrightPath) throw Error('Usage: check-build-page.mjs PLAYWRIGHT [CHROME]');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'base-ui-page-'));
const source = path.join(dir, 'fragment.html'), controller = path.join(dir, 'controller.js'), output = path.join(dir, 'app');
fs.writeFileSync(source, '<style>.probe { outline-width: 3px; outline-style: solid; }</style><main class="page__root page__flow"><h1 class="probe type-headline-md">Modular fixture</h1><button type="button" class="button__root" data-action="count">Count</button><output>0</output></main>');
fs.writeFileSync(controller, `createUIRuntime().mount({root:document.querySelector('main'),stateKey:'counter',definition:{initialState:0,reduce:s=>s+1,render:(root,s)=>root.querySelector('output').textContent=s,bind:({onAction})=>onAction('count',(event,target,dispatch)=>dispatch({type:'count'}))}});`);
const app = buildPage(source, output, controller);
const assets = localAssets(app);
for (const relative of ['styles/pages/page.css','styles/recipes/page.css','styles/shared/core.css','styles/vendor/fonts.css','runtime/kit.js','runtime/controller.js']) assert.ok(assets.some(a=>a.file===relative), relative);
assert.ok(!fs.readFileSync(app,'utf8').includes('<style>'));
const authored = path.join(output, 'styles/pages/page.css');
fs.appendFileSync(authored, '\n.probe { outline-width: 7px; }\n');
const saved = fs.readFileSync(authored,'utf8');
assert.throws(()=>buildPage(source,output,controller), /existing output/);
assert.equal(fs.readFileSync(authored,'utf8'),saved);
const empty = path.join(dir,'empty'); fs.mkdirSync(empty);
assert.throws(()=>buildPage(source,empty), /existing output/);
fs.writeFileSync(path.join(dir,'bad.html'), '<div style="color:var(--invented-page-token)">Unknown</div>');
assert.throws(()=>buildPage(path.join(dir,'bad.html'),path.join(dir,'bad')), /Unknown UI tokens/);
assert.equal(fs.existsSync(path.join(dir,'bad')), false);
fs.writeFileSync(path.join(dir,'bad.js'), 'import x from "remote";');
assert.throws(()=>buildPage(source,path.join(dir,'bad-script'),path.join(dir,'bad.js')));
assert.equal(fs.existsSync(path.join(dir,'bad-script')),false);
const review = path.join(dir,'review.json'); beginReview(app,review);
for (const relative of ['styles/recipes/page.css','styles/shared/tokens.css','runtime/controller.js','styles/vendor/fonts.css']) {
 const file=path.join(output,relative), before=fs.readFileSync(file);
 fs.appendFileSync(file,'\n/* changed */\n');
 assert.ok(verifyDelivery(review).errors.some(e=>e.includes('Local assets changed')),relative);
 fs.writeFileSync(file,before);
}
const pw=createRequire(import.meta.url)(path.resolve(playwrightPath));
const browser=await pw.chromium.launch({headless:true,...(executablePath?{executablePath}: {})});
const errors=[], remote=[];
let measured;
try {
 const context=await browser.newContext({offline:true});
 const page=await context.newPage();
 page.on('pageerror', e=>errors.push(e.message));
 page.on('request', r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
 await page.goto(pathToFileURL(app).href);
 await page.evaluate(()=>document.fonts.ready);
 await page.getByRole('button',{name:'Count'}).click();
 assert.equal(await page.locator('output').textContent(),'1');
 measured=await page.evaluate(()=>({outline:getComputedStyle(document.querySelector('h1')).outlineWidth,headingFont:getComputedStyle(document.querySelector('h1')).fontFamily,loadedFonts:[...document.fonts].filter(f=>f.status==='loaded').map(f=>f.family),buttonHeight:document.querySelector('button').getBoundingClientRect().height}));
 assert.equal(measured.outline,'7px');
 assert.match(measured.headingFont,/Bricolage/);
 assert.ok(measured.loadedFonts.some(f=>f.includes('Bricolage')));
 await page.evaluate(async()=>{await document.fonts.load('16px "IBM Plex Mono"');});
 assert.ok(await page.evaluate(()=>[...document.fonts].some(f=>f.family.includes('IBM Plex Mono')&&f.status==='loaded')));
 assert.ok(measured.buttonHeight>20);
 assert.deepEqual(errors,[]); assert.deepEqual(remote,[]);
} finally { await browser.close(); }
console.log(JSON.stringify({status:'pass',dir,dependencyStatus:'resolved',launchChecked:true,taskChecks:'passed',cases:['offline CSS and actual bundled fonts','classic runtime action','editable page CSS','existing/empty directory refusal','unknown tokens rejected before output','module controller rejected','recursive local asset review binding'],measured,scope:'Targeted modular packaging/interaction checks, not visual acceptance'},null,2));
