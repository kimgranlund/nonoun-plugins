// Maintainer projection of the mathematical source. Generated consumers are self-contained.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {geometryCell} from './lib/geometry-cell.mjs';
import {resolveGeometry, CFG} from '../../mathematical-design-system/scripts/lib/scale.mjs';

const source = new URL('../assets/foundation/maison/geometry.json', import.meta.url);
const target = new URL('../assets/foundation/maison/geometry.css', import.meta.url);
const steps = ['sm', 'md', 'lg'];
const profile = {schemaVersion:2, source:'mathematical-design-system/scripts/lib/scale.mjs', defaultTier:'product', tiers:{}};
for (const tier of Object.keys(CFG.tiers)) {
  profile.tiers[tier] = {};
  for (const scale of steps) for (const size of steps) {
    const v=resolveGeometry(tier,scale,size);
    profile.tiers[tier][`${scale}/${size}`] = geometryCell(v);
  }
}
const profileJSON=JSON.stringify(profile,null,2)+'\n';
if(process.argv.includes('--check')) assert.equal(fs.readFileSync(source,'utf8'),profileJSON,'Stale geometry.json');
else fs.writeFileSync(source,profileJSON);
const properties = Object.keys(profile.tiers.product['md/md']);
const value = (property, number) => `${number}${property.endsWith('ratio') ? '' : 'px'}`;
const cells = tier => steps.flatMap(scale => steps.flatMap(size => properties.map(property => {
  const number = profile.tiers[tier][`${scale}/${size}`][property];
  assert(Number.isFinite(number) && number > 0, `${tier}/${scale}/${size}/${property}`);
  return `  --m-cell-${scale}-${size}-${property}: ${value(property, number)};`;
}))).join('\n');
const lines = ['/* Generated by scripts/generate-geometry.mjs from mathematical-design-system/scripts/lib/scale.mjs. */', '@layer maison.tokens {', ':where(:root) { --corner-scale:1; --corner-shape:round; }', ':where(:root) {'];
for (const axis of ['scale', 'size']) for (const step of steps) lines.push(`  --m-${axis}-${step}: ${step === 'md' ? 1 : 0};`);
lines.push(cells(profile.defaultTier), '}');
for (const tier of Object.keys(profile.tiers)) lines.push(`:where([data-tier="${tier}"]) {`, cells(tier), '}');
for (const axis of ['scale', 'size']) for (const step of steps) {
  lines.push(`:where([data-${axis}="${step}"]) {`);
  for (const choice of steps) lines.push(`  --m-${axis}-${choice}: ${choice === step ? 1 : 0};`);
  lines.push('}');
}
lines.push(':where(*, :host) {');
for (const property of properties) {
  const terms = steps.flatMap(scale => steps.map(size => `var(--m-cell-${scale}-${size}-${property}) * var(--m-scale-${scale}, ${scale === 'md' ? 1 : 0}) * var(--m-size-${size}, ${size === 'md' ? 1 : 0})`));
  lines.push(`  --g-${property==='margin'?'unit':property}: calc(${terms.join(' + ')});`);
}
lines.push(...`
  --g-d:calc(var(--g-unit) * var(--density-factor,1));
  --g-margin:var(--g-d);
  --g-control-margin:max(0px,calc(var(--g-d) - var(--g-unit) / 2));
  --g-slot-height:calc(3 * var(--g-unit));
  --g-media:var(--g-slot-height);
  --g-height:calc(var(--g-slot-height) + 2 * var(--g-control-margin));
  --g-wrapper-padding:calc(var(--g-unit) * var(--control-gutter-ratio,.25));
  --g-label-padding:calc(var(--g-unit) / 2);
  --g-wrapper-gap:0px;
  --g-slot-gap:calc(var(--g-control-margin) / 2);
  --g-gutter:var(--g-d);
  --g-page-gutter:calc(4 * var(--g-d) * var(--page-gutter-ratio,1));
  --g-group-gutter:calc(var(--g-margin-reference,var(--g-d)) * var(--group-gutter-ratio,.5));
  --r-control:calc(var(--g-height) / 2 * var(--control-radius-amount,0));
  --r-mark:0px;
  --r-margin:var(--r-control);
  --r-listbox:var(--r-control);
  --r-listbox-option:max(calc(var(--g-slot-height) / 2 * var(--control-radius-amount,0)),calc(var(--r-listbox) * var(--control-radius-retained,0)));
  --r-group:0px;
  --r-group-inner:0px;
  --r-widget:var(--r-tile);
  --r-layout:var(--r-section);
`.trim().split('\n'));
for(const [name,m] of [['tile',2],['card',3],['section',4]]) lines.push(`  --g-${name}-margin:calc(${m} * var(--g-d));`, `  --g-${name}-gutter:calc(var(--g-${name}-margin) * var(--container-gutter-ratio,.75));`, `  --r-${name}:calc(var(--g-${name}-margin) * var(--container-radius-amount,0));`);
lines.push('  --g-table-cell-margin:calc(var(--g-control-margin) + var(--g-wrapper-padding));','  --g-table-clearance:var(--g-control-margin);','  --g-table-row-height:var(--g-height);','  --g-table-column-gap:calc(var(--g-control-margin) / 2);');
// Read aliases keep existing consumer CSS working; author with margin/gutter.
lines.push("  /* Deprecated read aliases; do not author new styles with these names. */");
for (const [oldName, newName] of [['--g-inset', '--g-margin'], ['--g-chip-inset', '--g-chip-margin'], ['--r-inset', '--r-margin']])
  lines.push(`  ${oldName}: var(${newName});`);
for (const scale of steps) for (const size of steps) for (const prefix of ['', 'chip-'])
  lines.push(`  --m-cell-${scale}-${size}-${prefix}inset: var(--m-cell-${scale}-${size}-${prefix}margin);`);
lines.push('}');
for(const [name,factor] of Object.entries({tight:.5,compact:.75,regular:1,spacious:1.25,loose:1.5}))lines.push(`[data-density=${name}] { --density-factor:${factor}; }`);
lines.push('}', '');
const css = lines.join('\n');
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), css, 'Stale geometry.css');
else fs.writeFileSync(target, css);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} four-tier geometry`);


// Ship self-contained current resolvers with the kit.
for(const file of ['scale.mjs','curvature.mjs']) {
 const content=fs.readFileSync(new URL('../../mathematical-design-system/scripts/lib/'+file,import.meta.url),'utf8');
 const dest=new URL('../assets/geometry/'+file,import.meta.url);
 if(process.argv.includes('--check'))assert.equal(fs.readFileSync(dest,'utf8'),content,'Stale resolver '+file);
 else fs.writeFileSync(dest,content);
}
