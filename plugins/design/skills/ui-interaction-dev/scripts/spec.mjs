#!/usr/bin/env node
// The interaction spec: references/spec.json is the source; references/spec.md is generated from it.
//   node scripts/spec.mjs            rewrite references/spec.md
//   node scripts/spec.mjs --check    exit 1 on any finding: an invalid rule, or spec.md out of step
//   node scripts/spec.mjs --area drag [--status validated]   print the matching rules
// Rules of the spec (validate): ids are unique and `area.name`; the area is declared; the rule states one obligation
// with MUST, SHOULD or MAY (RFC 2119, upper case); a sourced or contested rule cites at least one https source (a
// contested one two); a validated rule carries at least one record with a date, where, finding and check; no record
// names a host project.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const STATUSES = ['sourced', 'validated', 'contested']
const KEYWORD = /\b(MUST NOT|MUST|SHOULD NOT|SHOULD|MAY)\b/
const DATE = /^\d{4}-\d{2}-\d{2}$/

export const load = (p = join(ROOT, 'references', 'spec.json')) => JSON.parse(readFileSync(p, 'utf8'))

/** @param {any} spec @param {string[]} banned lower-case words no record may contain @returns {string[]} findings */
export function validate(spec, banned = []) {
  const out = [], seen = new Set()
  if (!spec || !Array.isArray(spec.rules) || typeof spec.areas !== 'object') return ['spec: needs "areas" and "rules"']
  for (const [i, r] of spec.rules.entries()) {
    const at = `rule ${r?.id ?? `#${i}`}`
    if (typeof r.id !== 'string' || !/^[a-z]+\.[a-z0-9-]+$/.test(r.id)) out.push(`${at}: id must be area.name in lower case`)
    else if (seen.has(r.id)) out.push(`${at}: duplicate id`)
    seen.add(r.id)
    if (!(r.area in spec.areas)) out.push(`${at}: area "${r.area}" is not declared`)
    else if (typeof r.id === 'string' && !r.id.startsWith(`${r.area}.`)) out.push(`${at}: id must start with its area "${r.area}."`)
    if (typeof r.rule !== 'string' || !KEYWORD.test(r.rule)) out.push(`${at}: rule must state MUST, SHOULD or MAY`)
    if (typeof r.why !== 'string' || r.why.length < 10) out.push(`${at}: needs a why`)
    if (!STATUSES.includes(r.status)) out.push(`${at}: status must be one of ${STATUSES.join(', ')}`)
    const src = r.sources ?? []
    if (src.some((s) => !/^https:\/\//.test(s))) out.push(`${at}: every source is an https URL`)
    if (r.status === 'sourced' && src.length < 1) out.push(`${at}: a sourced rule cites a source`)
    if (r.status === 'contested' && src.length < 2) out.push(`${at}: a contested rule cites the sources that disagree`)
    if (r.status === 'validated') {
      const v = r.validated ?? []
      if (!v.length) out.push(`${at}: a validated rule carries a validation record`)
      for (const x of v) {
        if (!DATE.test(x.on ?? '')) out.push(`${at}: a validation record needs "on" (YYYY-MM-DD)`)
        for (const k of ['where', 'finding', 'check']) if (typeof x[k] !== 'string' || !x[k].trim()) out.push(`${at}: a validation record needs "${k}"`)
      }
    } else if (r.validated?.length) out.push(`${at}: has validation records, so its status is validated`)
    const text = JSON.stringify(r).toLowerCase()
    for (const w of banned) if (text.includes(w)) out.push(`${at}: names a host project`)
  }
  return out
}

/** the generated reference */
export function render(spec) {
  const L = ['# Interaction spec', '', '<!-- generated by scripts/spec.mjs from references/spec.json: edit the JSON, then run node scripts/spec.mjs -->', '',
    'Keywords are RFC 2119. **validated** means an implementation\'s test proved the rule, with a negative control; **sourced** means a primary source states it and no test here has proved it yet; **contested** means the sources disagree.', '']
  const count = (s) => spec.rules.filter((r) => r.status === s).length
  L.push(`${spec.rules.length} rules: ${STATUSES.map((s) => `${count(s)} ${s}`).join(', ')}.`, '')
  for (const [area, title] of Object.entries(spec.areas)) {
    const rules = spec.rules.filter((r) => r.area === area)
    if (!rules.length) continue
    L.push(`## ${area}`, '', title + '.', '')
    for (const r of rules) {
      L.push(`### ${r.id} (${r.status})`, '', r.rule, '', `*Why:* ${r.why}`, '')
      if (r.note) L.push(`*Note:* ${r.note}`, '')
      for (const v of r.validated ?? []) L.push(`- Validated ${v.on}, ${v.where}: ${v.finding} Check: ${v.check}.`)
      if (r.validated?.length) L.push('')
      if (r.sources?.length) L.push(`Sources: ${r.sources.map((s) => `<${s}>`).join(', ')}`, '')
    }
  }
  return L.join('\n').replace(/\n+$/, '\n')
}

// host-project names no record may contain, stored reversed so this file does not contain them either
export const BANNED = ['msinredom latnemurtsni'].map((w) => [...w].reverse().join(''))

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2), spec = load(), md = join(ROOT, 'references', 'spec.md')
  const flag = (k) => { const i = args.indexOf(k); return i < 0 ? null : args[i + 1] }
  if (flag('--area') || flag('--status')) {
    for (const r of spec.rules.filter((x) => (!flag('--area') || x.area === flag('--area')) && (!flag('--status') || x.status === flag('--status'))))
      console.log(`${r.id} (${r.status}): ${r.rule}`)
  } else if (args.includes('--check')) {
    const found = validate(spec, BANNED)
    let current = ''; try { current = readFileSync(md, 'utf8') } catch { /* missing */ }
    if (current !== render(spec)) found.push('references/spec.md is out of step: run node scripts/spec.mjs')
    for (const f of found) console.log(f)
    console.log(found.length ? `spec: ${found.length} finding(s)` : `spec: ${spec.rules.length} rules ok`)
    process.exit(found.length ? 1 : 0)
  } else {
    const found = validate(spec, BANNED)
    if (found.length) { for (const f of found) console.log(f); process.exit(1) }
    writeFileSync(md, render(spec)); console.log(`wrote references/spec.md (${spec.rules.length} rules)`)
  }
}
