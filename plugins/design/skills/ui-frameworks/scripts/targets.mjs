// Writes the recipes of the framework targets (docs/specs/targets.md, X3; CSS contract, C23 and C24).
//
//   node scripts/targets.mjs           write kit/<target>/<id>/<id>.css for every component a manifest marks
//                                      built for that target, and kit/<target>/styles/kit.css
//   node scripts/targets.mjs --check   write nothing; exit 1 if a file is missing, stale, or left over
//   --against <dir>                    holds the files of another folder, laid out as the project, against the
//                                      sources, so a test can show a stale copy without touching the real one
//
// A target's recipe is the Web Components recipe rewritten by scripts/rewrite-recipe.mjs, and nothing else.
// Its kit.css is the shared stylesheets of kit/styles, with native.css (X11), then every built recipe of the target, in id order.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { rewrite, variantsOf } from './rewrite-recipe.mjs';
import { readManifests } from './manifests.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** The framework targets, the folder of each under kit/. Solid joins when it is built. */
export const TARGETS = ['react', 'svelte'];
const PREFIX = 'ui';
/** native.css resets what a native root brings (X11). */
const SHARED = ['reset.css', 'native.css', 'tokens.css', 'icons.css'];

/** The ids a manifest marks built for a target. @param {Record<string, any>} manifests @param {string} target */
export const builtFor = (manifests, target) => Object.keys(manifests).sort().filter((id) => manifests[id].kind === 'component' && manifests[id].targets[target] === 'built');

/**
 * Every file the generator owns, with what it should hold: path from the project root to text.
 * @param {Record<string, any>} manifests @param {(file: string) => string} read  Reads a file of the project.
 * @returns {Record<string, string>}
 */
export function outputs(manifests, read = (file) => fs.readFileSync(path.join(root, file), 'utf8')) {
  /** @type {Record<string, string>} */
  const out = {};
  for (const target of TARGETS) {
    const ids = builtFor(manifests, target);
    for (const id of ids) out[`kit/${target}/${id}/${id}.css`] = rewrite(read(`kit/components/${id}/${id}.css`), { id, prefix: PREFIX, variants: variantsOf(manifests[id]) });
    const shared = SHARED.filter((f) => fs.existsSync(path.join(root, 'kit/styles', f))).map((f) => `../../styles/${f}`);
    out[`kit/${target}/styles/kit.css`] = `@layer reset, base, tokens, recipes, utilities;\n\n/* The ${target} target's index (X3). Link this file ahead of any component.\n   Generated by scripts/targets.mjs from the components marked built for ${target}. Do not edit. */\n${[...shared, ...ids.map((id) => `../${id}/${id}.css`)].map((f) => `@import '${f}';`).join('\n')}\n`;
  }
  return out;
}

/** The generated recipes on disk that no built component accounts for. @param {Record<string, string>} wanted @param {string} [base] */
export function leftOver(wanted, base = root) {
  const found = [];
  for (const target of TARGETS) {
    const dir = path.join(base, 'kit', target);
    if (!fs.existsSync(dir)) continue;
    for (const id of fs.readdirSync(dir)) {
      const file = `kit/${target}/${id}/${id}.css`;
      if (id !== 'styles' && fs.existsSync(path.join(base, file)) && !(file in wanted)) found.push(file);
    }
  }
  return found;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const onlyCheck = process.argv.includes('--check');
  const base = process.argv.includes('--against') ? path.resolve(process.argv[process.argv.indexOf('--against') + 1]) : root;
  const wanted = outputs(readManifests());
  let problems = 0;
  for (const [file, text] of Object.entries(wanted)) {
    const target = path.join(base, file);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (current === text) continue;
    if (onlyCheck) { problems++; console.log(`ERROR ${file} X3: it is ${current === null ? 'missing' : 'stale'}; run node scripts/targets.mjs`); }
    else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, text); console.log(`wrote ${file}`); }
  }
  for (const file of leftOver(wanted, base)) {
    if (onlyCheck) { problems++; console.log(`ERROR ${file} X3: no manifest marks its component built for this target; run node scripts/targets.mjs`); }
    else { fs.rmSync(path.join(base, file)); console.log(`removed ${file}`); }
  }
  console.log(problems ? `${problems} problem(s)` : `${Object.keys(wanted).length} file(s) of ${TARGETS.length} target(s)${onlyCheck ? ' match their sources' : ' up to date'}`);
  process.exit(problems ? 1 : 0);
}
