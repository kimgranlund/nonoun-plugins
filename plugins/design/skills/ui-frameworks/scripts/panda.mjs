// Writes kit/panda/preset.js, the Panda preset of D16: the state matrix's conditions under their Panda names
// (C25) and the kit's tokens under paths that begin with `kit` (C26). It sets no layers (C27): the kit's
// sheets already use Panda's layer names (D27). A Panda project adds the preset and loads the kit's CSS as it is.
//
//   node scripts/panda.mjs            writes the preset
//   node scripts/panda.mjs --check    writes nothing; fails when the preset is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build as tokens } from './tokens.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');

/** A material token that is a colour, and one that is a shadow; the rest have no Panda category. */
const isColour = (name) => /(-face|^--ink|^--line|^--on-display|^--accent|^--bg)$/.test(name);
const isShadow = (name) => /-shadow(-\d+)?$/.test(name);
const isRadius = (name) => /curvature|radius/.test(name);

export function preset() {
  const states = JSON.parse(read('references/states.json'));
  /** @type {Record<string, string>} */
  const conditions = {};
  for (const s of states.states) if (s.panda) conditions[s.panda] = `&${s.condition}`;
  for (const e of states.environment) if (e.panda) conditions[e.panda] = e.query.startsWith('@') ? e.query : `&${e.query}`;

  const { text, geometryNames, materialNames } = tokens();
  const ref = (name) => ({ value: `var(${name})` });
  const colours = [...new Set([...text.matchAll(/^\s+(--colors-[a-z0-9-]+)\s*:/gm)].map((m) => m[1]))].sort();
  const colors = {}, shadows = {}, sizes = {}, radii = {};
  for (const name of colours) colors[name.slice('--colors-'.length)] = ref(name);
  for (const name of [...new Set(materialNames)].sort()) {
    if (isColour(name)) colors[name.slice(2)] = ref(name);
    else if (isShadow(name)) shadows[name.slice(2)] = ref(name);
  }
  for (const name of geometryNames) (isRadius(name) ? radii : sizes)[name.slice(2)] = ref(name);
  return {
    name: 'ui-kit',
    conditions: { extend: conditions },
    theme: { extend: { tokens: { colors: { kit: colors }, shadows: { kit: shadows }, sizes: { kit: sizes }, spacing: { kit: sizes }, radii: { kit: radii } } } },
  };
}

export const source = () => `// Generated by scripts/panda.mjs from references/states.json and kit/styles/tokens.css. Do not edit.
// A Panda project: presets: [kit], then load kit/styles/kit.css as it is (D16). No layers are set (C27).
export default ${JSON.stringify(preset(), null, 2)};
`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = path.join(root, 'kit/panda/preset.js');
  const text = source();
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (current !== text) { console.log(`ERROR kit/panda/preset.js is ${current === null ? 'missing' : 'stale'}; run node scripts/panda.mjs`); process.exit(1); }
    console.log('the Panda preset matches the state matrix and the tokens');
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text);
    const p = preset();
    console.log(`wrote kit/panda/preset.js: ${Object.keys(p.conditions.extend).length} conditions, ${Object.keys(p.theme.extend.tokens.colors.kit).length} colours`);
  }
}
