// Writes <id>.props.js beside each component manifest: the part of the contract a class needs at run time (D42).
//
//   node scripts/props.mjs           write the files
//   node scripts/props.mjs --check   exit 1 if a file is missing or differs from its manifest
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// --components <dir> reads another folder of components, so a test can show a stale file without touching a real one.
const components = process.argv.includes('--components') ? path.resolve(process.argv[process.argv.indexOf('--components') + 1]) : path.join(root, 'kit/components');
const check = process.argv.includes('--check');
const TYPES = ['boolean', 'string', 'number', 'enum'];

/** @param {any} manifest */
function render(manifest) {
  const props = {};
  for (const [name, a] of Object.entries(manifest.attributes)) {
    if (!TYPES.includes(a.type)) throw new Error(`${manifest.id}: the attribute "${name}" has the unknown type "${a.type}"`);
    if (a.type === 'enum' && !(a.values ?? []).includes(a.default)) throw new Error(`${manifest.id}: the default of "${name}" is not one of its values`);
    props[name] = { type: a.type, ...(a.values ? { values: a.values } : {}), ...(a.default !== undefined ? { default: a.default } : {}) };
  }
  const parts = {};
  for (const [name, p] of Object.entries(manifest.parts)) {
    if (p.kind !== 'element') continue;
    parts[name] = { tag: p.tag, at: p.at, ...(p.attrs ? { attrs: p.attrs } : {}), ...(p.lazy ? { lazy: true } : {}) };
  }
  const line = (name, type, value) => `/** @type {${type}} */\nexport const ${name} = ${JSON.stringify(value, null, 2)};\n`;
  return `// Generated by scripts/props.mjs from ${manifest.id}.manifest.json. Do not edit.\n// @ts-check\n\n`
    + line('props', "Record<string, import('../../foundation/element.js').Prop>", props) + '\n'
    + line('parts', "Record<string, import('../../foundation/element.js').Part>", parts) + '\n'
    + line('role', manifest.role == null ? 'null' : 'string', manifest.role ?? null) + '\n'
    + line('tabindex', manifest.tabindex == null ? 'null' : 'number', manifest.tabindex ?? null) + '\n'
    + line('resets', 'string[]', manifest.resets ?? []);
}

let problems = 0;
for (const id of fs.readdirSync(components)) {
  const manifestFile = path.join(components, id, `${id}.manifest.json`);
  if (!fs.existsSync(manifestFile)) continue;
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  if (manifest.id !== id) { console.log(`ERROR ${id}: the manifest's id is "${manifest.id}"`); problems++; continue; }
  if (manifest.kind !== 'component') continue;
  const target = path.join(components, id, `${id}.props.js`);
  const wanted = render(manifest);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current === wanted) continue;
  if (check) { console.log(`ERROR kit/components/${id}/${id}.props.js is ${current === null ? 'missing' : 'stale'}; run node scripts/props.mjs`); problems++; }
  else { fs.writeFileSync(target, wanted); console.log(`wrote kit/components/${id}/${id}.props.js`); }
}
console.log(problems ? `${problems} problem(s)` : check ? 'prop schemas match their manifests' : 'done');
process.exit(problems ? 1 : 0);
