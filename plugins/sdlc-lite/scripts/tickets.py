        root = case(filer('filer-L1.md', 'None', 'We should add retry to fetch and document the flag.'))
        before = snap(root)
        rc, _, err = run(root, 'close', ('alpha',))
        expect(f'(f) prose follow-ups refuse: rc={rc} {err!r}', rc == 1 and snap(root) == before)

