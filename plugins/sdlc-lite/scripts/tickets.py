            before = snap(root)
            rc, _, err = run(root, 'new', ('feature', '0007-gamma'), **kw)
            expect(f'new 0007-gamma in numbered mode ({label}) refuses on the double prefix: rc={rc} {err!r}',
                   rc == 1 and 'double' in err and snap(root) == before)

