        root = case(good)
        run(root, 'close', ('alpha',))
        before = snap(root)
        rc, _, err = run(root, 'close', ('alpha', True))
        expect(f'(g) second close refuses: rc={rc} {err!r}', rc == 1 and 'already closed' in err and snap(root) == before)

