        rc, _, err = run(case(mutations[0][1]), 'roadmap')
        expect('roadmap refuses on a bad ticket', rc == 1 and "type='epic'" in err)
        rc, _, err = run(case(mutations[0][1]), 'new', ('idea', 'delta'))
